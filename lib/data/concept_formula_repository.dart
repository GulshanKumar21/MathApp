  static List<ConceptFormulaModel> getByPillar(ConceptPillar pillar) {
    return formulas.where((f) => f.pillar == pillar).toList();
  }

  static ConceptFormulaModel? getById(String id) {
    try {
      return formulas.firstWhere((f) => f.id == id);
    } catch (_) {
      return null;
    }
  }

  static List<ConceptFormulaModel> search(String query) {
    if (query.trim().isEmpty) return List.from(formulas);
    final q = query.trim().toLowerCase();
    return formulas.where((f) {
      final inTitle = f.title.toLowerCase().contains(q);
      final inFormula = f.formula.toLowerCase().contains(q);
      final inSubtitle = f.subtitle.toLowerCase().contains(q);
      final inPillar = f.pillar.displayName.toLowerCase().contains(q) ||
          f.pillar.shortName.toLowerCase().contains(q) ||
          f.pillar.ordinalLabel.toLowerCase().contains(q);
      final inKeyConditions = f.keyConditions.any((cond) => cond.toLowerCase().contains(q));
      final inExplanation = f.explanation.toLowerCase().contains(q);
      return inTitle || inFormula || inSubtitle || inPillar || inKeyConditions || inExplanation;
    }).toList();
  }
